_pending: dict[tuple[int, int], tuple[float, str, tuple[str, ...]]] = {}
_last_index: dict[tuple[int, int, str], int] = {}


def _normalize(value: str) -> str:
    return re.sub(r"[^а-яёa-z0-9]+", " ", value.lower()).strip()


def normalize_category(value: str | None) -> str | None:
    if not value:
        return None
    value = _normalize(value).replace(" ", "_")
    aliases = {"обычная": "обычные", "смешная": "смешные", "логическая": "логические", "логика": "логические", "с_подвохом": "с_подвохом", "подвох": "с_подвохом"}
    return aliases.get(value, value if value in RIDDLES else None)


def new_riddle(chat_id: int, user_id: int, category: str | None = None) -> str:
    category = normalize_category(category) or random.choice(tuple(RIDDLES))
    items = RIDDLES[category]
    key = (chat_id, user_id, category)
    choices = [i for i in range(len(items)) if i != _last_index.get(key)] or [0]
    index = random.choice(choices)
    _last_index[key] = index
    question, answers = items[index]
    _pending[(chat_id, user_id)] = (time.monotonic(), question, answers)
    return f"🧩 Категория: {category.replace('_', ' ')}\n{question}\nОтветь обычным сообщением."


def check_answer(chat_id: int, user_id: int, text: str) -> str | None:
    pending = _pending.get((chat_id, user_id))
    if not pending:
        return None
    created, _question, answers = pending
    if time.monotonic() - created > RIDDLE_TTL:
        _pending.pop((chat_id, user_id), None)
        return None
    _pending.pop((chat_id, user_id), None)
    guess = _normalize(text)
    valid = any(guess == _normalize(a) or _normalize(a) in guess for a in answers)
    if valid:
        return random.choice(("✅ Верно! Отличная работа.", "✅ Точно! Загадка раскрыта.", "✅ Правильный ответ. Логика на месте."))
    return f"❌ Не угадал. Правильный ответ: {answers[0]}."


def has_pending(chat_id: int, user_id: int) -> bool:
    return (chat_id, user_id) in _pending
