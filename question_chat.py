def detect(text: str) -> str | None:
    normalized = " ".join(text.lower().strip().split())
    if any(phrase in normalized for phrase in KNOWN_SMALL_TALK):
        return None
    if "?" not in normalized and not re.match(r"^(?:почему|зачем|как|что|кто|где|когда|можно ли|как думаешь)", normalized):
        return None
    if re.search(r"\b(почему|зачем)\b", normalized):
        return "why"
    if re.search(r"(как думаешь|твоё мнение|как считаешь)", normalized):
        return "opinion"
    if re.search(r"\bкак\b", normalized):
        return "how"
    if re.search(r"\b(можно|стоит|разрешено)\b", normalized):
        return "permission"
    if re.search(r"\b(или|выбрать|лучше)\b", normalized):
        return "choice"
    return "general"


def reply_for(user_id: int, text: str) -> str | None:
    category = detect(text)
    if category is None:
        return None
    bank = BANKS[category]
    combinations = [f"{start} {end}" for start in bank["starts"] for end in bank["ends"]]
    return choose(f"question:{user_id}:{category}", combinations)
